import { Building2, CalendarClock, Check, Clock, FlaskConical, Globe, MapPin, Phone, UserRound, Video, X } from "lucide-react";
import { APPLICATION_STATUSES } from "../../domain/constants.js";
import { INTERVIEW_STATUSES, INTERVIEW_TYPES, STAGE_ORDER } from "../../domain/recruitment.js";
import { formatDateTime, formatDuration, formatRelative, formatTime, viewerTimeZone } from "../../lib/format.js";
import { buttonClasses } from "../Button.jsx";
import Badge, { StatusBadge } from "../ui/Badge.jsx";

export const INTERVIEW_TYPE_ICONS = { video: Video, phone: Phone, onsite: Building2 };

export function ApplicationStatusBadge({ status }) {
  return <StatusBadge map={APPLICATION_STATUSES} value={status} />;
}

export function InterviewStatusBadge({ interview }) {
  if (interview.status === "scheduled" && interview.rescheduleCount > 0) return <Badge tone="warning">Rescheduled</Badge>;
  return <StatusBadge map={INTERVIEW_STATUSES} value={interview.status} />;
}

// Progress through the pipeline. A rejected application shows where it stopped.
export function StageTracker({ status, history = [], compact = false }) {
  const rejected = status === "rejected";
  // The furthest happy-path stage reached, from the history (so a rejection keeps its context).
  const reached = Math.max(0, ...history.map((h) => STAGE_ORDER.indexOf(h.status)), STAGE_ORDER.indexOf(status));
  const steps = STAGE_ORDER.map((key, i) => ({ key, label: APPLICATION_STATUSES[key].label, done: i < reached || (i === reached && status === "hired"), current: i === reached && !rejected && status !== "hired" }));

  return (
    <ol aria-label="Recruitment progress" className={`flex items-start ${compact ? "gap-1" : "gap-1.5"}`}>
      {steps.map((step, i) => {
        const stoppedHere = rejected && i === reached;
        return (
          <li key={step.key} className="flex min-w-0 flex-1 flex-col items-center text-center" aria-current={step.current ? "step" : undefined}>
            <div className="flex w-full items-center">
              <span className={`h-0.5 flex-1 ${i === 0 ? "invisible" : step.done || step.current || stoppedHere ? "bg-accent-400" : "bg-gray-200"}`} />
              <span
                className={`flex shrink-0 items-center justify-center rounded-full ${compact ? "h-5 w-5" : "h-7 w-7"} ${
                  stoppedHere
                    ? "bg-error text-white"
                    : step.done
                      ? "bg-accent-500 text-white"
                      : step.current
                        ? "bg-white text-accent-600 ring-2 ring-accent-500"
                        : "bg-gray-100 text-gray-400"
                }`}
              >
                {stoppedHere ? (
                  <X aria-hidden="true" size={compact ? 11 : 14} strokeWidth={2.5} />
                ) : step.done ? (
                  <Check aria-hidden="true" size={compact ? 11 : 14} strokeWidth={2.5} />
                ) : (
                  <span className={`rounded-full ${compact ? "h-1.5 w-1.5" : "h-2 w-2"} ${step.current ? "bg-accent-500" : "bg-gray-300"}`} />
                )}
              </span>
              <span className={`h-0.5 flex-1 ${i === steps.length - 1 ? "invisible" : step.done ? "bg-accent-400" : "bg-gray-200"}`} />
            </div>
            {!compact && (
              <span className={`mt-1.5 hidden text-[11px] leading-tight sm:block ${step.current ? "font-semibold text-accent-700" : stoppedHere ? "font-semibold text-error" : step.done ? "text-gray-700" : "text-gray-400"}`}>
                {stoppedHere ? "Closed" : step.label}
              </span>
            )}
            <span className="sr-only">
              {step.label}: {stoppedHere ? "application closed at this stage" : step.done ? "done" : step.current ? "current stage" : "not reached"}
            </span>
          </li>
        );
      })}
    </ol>
  );
}

// A link generated by CareerBridge is a demo room, not an integrated meeting service.
export function MeetingLinkNote({ interview }) {
  if (!interview.meetingUrl) return null;
  return interview.isDemoLink ? (
    <p className="flex items-start gap-1.5 text-[11px] text-cyan-700">
      <FlaskConical aria-hidden="true" size={13} className="mt-px shrink-0" />
      Demo meeting room generated for this MVP. CareerBridge has no integrated video service yet.
    </p>
  ) : (
    <p className="text-[11px] text-gray-500">Meeting link provided by the recruiter.</p>
  );
}

export function JoinInterviewButton({ interview, size = "sm", className = "" }) {
  if (interview.status !== "scheduled" || !interview.meetingUrl) return null;
  return (
    <a href={interview.meetingUrl} target="_blank" rel="noopener noreferrer" className={buttonClasses("solid", className, size)}>
      <Video aria-hidden="true" size={16} /> Join interview
    </a>
  );
}

function Row({ icon: Icon, label, children }) {
  return (
    <div className="flex items-start gap-2.5">
      <Icon aria-hidden="true" size={16} strokeWidth={1.8} className="mt-0.5 shrink-0 text-gray-400" />
      <div className="min-w-0">
        <dt className="text-[11px] text-gray-500">{label}</dt>
        <dd className="text-[13px] break-words text-gray-900">{children}</dd>
      </div>
    </div>
  );
}

// Logistics shown to both sides. Times are shown in the interview's zone, plus the viewer's own if different.
export function InterviewDetails({ interview }) {
  const local = viewerTimeZone();
  const TypeIcon = INTERVIEW_TYPE_ICONS[interview.type] ?? Video;
  const end = new Date(new Date(interview.scheduledAt).getTime() + interview.durationMinutes * 60000).toISOString();

  return (
    <dl className="grid gap-3 sm:grid-cols-2">
      <Row icon={CalendarClock} label="Date and time">
        {formatDateTime(interview.scheduledAt, interview.timeZone)}–{formatTime(end, interview.timeZone)}
        {interview.status === "scheduled" && <span className="block text-xs text-gray-500">{formatRelative(interview.scheduledAt)}</span>}
      </Row>
      <Row icon={Globe} label="Time zone">
        {interview.timeZone}
        {local !== interview.timeZone && <span className="block text-xs text-gray-500">Your time: {formatDateTime(interview.scheduledAt, local)}</span>}
      </Row>
      <Row icon={Clock} label="Duration">{formatDuration(interview.durationMinutes)}</Row>
      <Row icon={TypeIcon} label="Interview type">{INTERVIEW_TYPES[interview.type]?.label}</Row>
      <Row icon={UserRound} label="Interviewer">{interview.interviewer}</Row>
      {interview.type === "onsite" ? (
        <Row icon={MapPin} label="Address">{interview.location}</Row>
      ) : (
        interview.meetingUrl && (
          <Row icon={Video} label="Meeting link">
            <a href={interview.meetingUrl} target="_blank" rel="noopener noreferrer" className="font-medium text-accent-600 hover:underline">
              {interview.meetingUrl.replace(/^https:\/\//, "")}
            </a>
          </Row>
        )
      )}
      {interview.instructions && (
        <div className="sm:col-span-2">
          <dt className="text-[11px] text-gray-500">Instructions</dt>
          <dd className="mt-0.5 rounded-md bg-gray-50 px-3 py-2 text-[13px] whitespace-pre-line text-gray-700">{interview.instructions}</dd>
        </div>
      )}
    </dl>
  );
}
